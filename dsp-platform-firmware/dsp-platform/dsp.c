/* User DSP callback function. */
static dsp_function_t dspFunction = NULL;
static void* dspFunctionArgs = NULL;

/* DSP input buffer and output buffers. */
uint8_t DSP_inputBuffer[DSP_SAMPLE_SIZE];
uint8_t DSP_outputBuffer[DSP_SAMPLE_SIZE];

/* DSP sample index. */
int DSP_sampleIndex = 0;

/* Timer handle and parameters. */
static LGPTimerLPF3_Handle dspTimerHandle;
static LGPTimerLPF3_Params dspTimerParams;

/* ADC Handle. */
static ADC_Handle dspAdcHandle;
static ADC_Params dspAdcParams;
static uint16_t adcResult;

/**
 *   Modified ADC driver function.
 */
int_fast16_t ADCLPF3_convert_custom(ADC_Handle handle, uint16_t *value)
{
    ADCLPF3_HWAttrs const *hwAttrs;
    int_fast16_t conversionResult = ADC_STATUS_SUCCESS;
    uint32_t conversionValue;
    uint32_t interruptStatus;
    //uint32_t semaphorePendTimeout = HwiP_inISR() ? SemaphoreP_NO_WAIT : SemaphoreP_WAIT_FOREVER;

    DebugP_assert(handle);

    /* Get handle */
    hwAttrs = handle->hwAttrs;

    /* Acquire the lock for this particular ADC handle */
    //if (SemaphoreP_pend(&ADCLPF3_adcSemaphore, semaphorePendTimeout) != SemaphoreP_OK)
    //{
    //    return ADC_STATUS_ERROR;
    //}

    /* Set constraints to guarantee operation */
    //Power_setConstraint(PowerLPF3_DISALLOW_STANDBY);

    /* Make sure conversion is disabled to allow configuration changes */
    ADCDisableConversion();

    /* Specify range of ctrl registers for conversion. Use ctrl register 0 */
    ADCSetMemctlRange(0, 0);

    /* Set clock-divider and sampling duration */
    ADCSetSampleDuration(hwAttrs->adcClkkDivider, hwAttrs->samplingDuration);

    /* Set sampling mode to auto, meaning the sample duration is determined by
     * sample duration configured above.
     */
    ADCSetSamplingMode(ADC_SAMPLE_MODE_AUTO);

    /* Set resolution */
    ADCSetResolution(hwAttrs->resolutionBits);

    /* Set reference source */
    ADCSetInput(hwAttrs->refSource, hwAttrs->internalChannel, 0);

    /* Pass correct offset-value to ADC peripheral, depending on reference source */
    ADCSetAdjustmentOffset(hwAttrs->refSource);

    /* Configure ADC to only do one conversion */
    ADCSetSequence(ADC_SEQUENCE_SINGLE);

    /* Use software trigger source */
    ADCSetTriggerSource(ADC_TRIGGER_SOURCE_SOFTWARE);

    /* Enable conversion. ADC will wait for trigger. */
    ADCEnableConversion();

    /* Start conversion. No need to call ADCStopConversion() since that is only
     * needed in manual sampling mode.
     */
    ADCStartConversion();

    /* There is a delay of 9 cycles on CC23X0 and 18 cycles on CC27XX between
     * writing the SC_START bit, and the BUSY-bit going high. If we start
     * polling too early, we will miss it. Delay 6 loops, where each loop is
     * minimum 3 cycles.
     */
    CPUDelay(6);

    /* Read out conversion (blocking while ADC is busy) */
    conversionValue = ADCReadResult(0);

    /* Check if something went wrong. (Underflow or overflow) */
    interruptStatus = ADCRawInterruptStatus();

    if (interruptStatus & (ADC_INT_OVIFG | ADC_INT_UVIFG))
    {
        conversionResult = ADC_STATUS_ERROR;
    }

    /* Clear all interrupts generated by ADC */
    ADCClearInterrupt(0xFFFFFFFF);

    /* Allow entering standby again after ADC conversion complete */
    //Power_releaseConstraint(PowerLPF3_DISALLOW_STANDBY);

    /* Release the lock for this particular ADC handle */
    //SemaphoreP_post(&ADCLPF3_adcSemaphore);

    /* If we want to return the trimmed value, calculate it here. */
    if (hwAttrs->returnAdjustedVal)
    {
        uint16_t gain   = ADCGetAdjustmentGain(hwAttrs->refSource);
        conversionValue = ADCAdjustValueForGain(conversionValue, hwAttrs->resolutionBits, gain);
    }

    *value = conversionValue;

    /* Return the status-code of the conversion */
    return conversionResult;
}


static void dspTimerIsr(LGPTimerLPF3_Handle handle, LGPTimerLPF3_IntMask interruptMask)
{
    int status;

    HWREGB(GPIO_BASE + GPIO_O_DOUT3_0 + CONFIG_TEST_GPIO) = 1;

    status = ADCLPF3_convert_custom(dspAdcHandle, &adcResult);

    if(status)
    {
        __asm volatile("bkpt 0");
    }

    if(DSP_sampleIndex < DSP_SAMPLE_SIZE)
    {
        DSP_inputBuffer[DSP_sampleIndex] = (uint8_t)(adcResult >> 4);

        if(dspFunction)
        {
            DSP_outputBuffer[DSP_sampleIndex] = dspFunction(DSP_inputBuffer[DSP_sampleIndex],dspFunctionArgs);
        }
        else 
        {
            DSP_outputBuffer[DSP_sampleIndex] = 0;
        }

        DSP_sampleIndex++;
    }
    else 
    {
        if(dspFunction)
        {
            (void)dspFunction(DSP_inputBuffer[DSP_sampleIndex],dspFunctionArgs);
        }
    }

    HWREGB(GPIO_BASE + GPIO_O_DOUT3_0 + CONFIG_TEST_GPIO) = 0;
}

void DSP_init()
{
    /* Initialize ADC. */

    ADC_Params_init(&dspAdcParams);

    dspAdcParams.isProtected = true;

    dspAdcHandle = ADC_open(CONFIG_ADC_0, &dspAdcParams);

    if(!dspAdcHandle)
    {
        __asm volatile("bkpt 0");
    }

    /* Initialize DSP loop timer. */

    LGPTimerLPF3_Params_init(&dspTimerParams);

    dspTimerParams.prescalerDiv = 0;
    dspTimerParams.hwiCallbackFxn = dspTimerIsr;

    dspTimerHandle = LGPTimerLPF3_open(CONFIG_LGPTIMER_1, &dspTimerParams);

    if(!dspTimerHandle)
    {
        __asm volatile("bkpt 0");
    }

    LGPTimerLPF3_setInitialCounterTarget(dspTimerHandle, (4800 - 1), true);
    LGPTimerLPF3_enableInterrupt(dspTimerHandle, LGPTimerLPF3_INT_TGT);
}

void DSP_reset()
{
    DSP_sampleIndex = 0;
    memset( DSP_inputBuffer, 0, sizeof(DSP_inputBuffer) );
    memset( DSP_outputBuffer, 0, sizeof(DSP_outputBuffer) );
}

void DSP_setLoopFrequency(int frequency)
{
    HWREG(LGPT0_BASE + LGPT_O_TGT) = (uint32_t)((double)(48000000) / (double)frequency); 
}

void DSP_setFunction(dsp_function_t function, void* args)
{
    dspFunction = function;
    dspFunctionArgs = args;
}

void DSP_start()
{
    LGPTimerLPF3_start(dspTimerHandle, LGPTimerLPF3_CTL_MODE_UP_PER);
}

void DSP_stop()
{
    LGPTimerLPF3_stop(dspTimerHandle);
}

void DSP_numberOfSamples()
{
    return DSP_sampleIndex;
}

int DSP_getSampleBufferSize()
{
    return DSP_SAMPLE_SIZE;
}

uint8_t DSP_getInputSample(int index)
{
    return DSP_inputBuffer[index];
}

uint8_t DSP_getOutputSample(int index)
{
    return DSP_outputBuffer[index];    
}
